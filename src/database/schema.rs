mod manifest;
pub use manifest::{Column, ColumnType, Table, TABLES};

use diesel::{prelude::QueryableByName, sql_query, sql_types::Text};
use diesel_async::{AsyncConnection, AsyncPgConnection, RunQueryDsl};

#[derive(QueryableByName)]
struct NameRow {
    #[diesel(sql_type = Text)]
    name: String,
}

pub async fn run_autonomous_sync(database_url: &str) -> Result<(), String> {
    let mut connection = AsyncPgConnection::establish(database_url)
        .await
        .map_err(|error| format!("connect for schema sync: {error}"))?;
    diesel_async::SimpleAsyncConnection::batch_execute(
        &mut connection,
        "SELECT pg_advisory_lock(731946205118::bigint)",
    )
    .await
    .map_err(|error| format!("lock schema sync: {error}"))?;

    for table in TABLES {
        sync_table(&mut connection, table).await?;
    }
    ensure_constraints(&mut connection).await?;
    ensure_record_store(&mut connection).await?;
    ensure_audit_append_only(&mut connection).await?;
    diesel_async::SimpleAsyncConnection::batch_execute(
        &mut connection,
        "SELECT pg_advisory_unlock(731946205118::bigint)",
    )
    .await
    .map_err(|error| format!("unlock schema sync: {error}"))?;
    Ok(())
}

async fn ensure_record_store(connection: &mut AsyncPgConnection) -> Result<(), String> {
    diesel_async::SimpleAsyncConnection::batch_execute(
        connection,
        r#"CREATE TABLE IF NOT EXISTS hr_records (
           id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
           record_type TEXT NOT NULL,
           source_id TEXT NOT NULL,
           data JSONB NOT NULL CHECK (jsonb_typeof(data) = 'object'),
           archived_at TIMESTAMPTZ,
           created_by BIGINT REFERENCES users(id),
           updated_by BIGINT REFERENCES users(id),
           created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
           updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
           UNIQUE(record_type, source_id)
         );
         CREATE INDEX IF NOT EXISTS ix_hr_records_type_active ON hr_records(record_type, created_at DESC) WHERE archived_at IS NULL;
         CREATE TABLE IF NOT EXISTS hr_record_history (
           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
           record_id UUID NOT NULL,
           action TEXT NOT NULL CHECK (action IN ('created','updated','archived','restored')),
           actor_user_id BIGINT NOT NULL REFERENCES users(id),
           before_data JSONB, after_data JSONB, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
         );
         CREATE INDEX IF NOT EXISTS ix_hr_record_history_record ON hr_record_history(record_id, id DESC);
         CREATE TABLE IF NOT EXISTS hr_record_unique_claims (
           record_type TEXT NOT NULL, field_key TEXT NOT NULL, normalized_value TEXT NOT NULL,
           record_id UUID NOT NULL REFERENCES hr_records(id) ON DELETE CASCADE,
           PRIMARY KEY(record_type, field_key, normalized_value), UNIQUE(record_id, field_key)
         );
         CREATE INDEX IF NOT EXISTS ix_hr_record_unique_record ON hr_record_unique_claims(record_id);
         ALTER TABLE hr_record_history ADD COLUMN IF NOT EXISTS source_actor_user_id BIGINT;
         CREATE TABLE IF NOT EXISTS hr_rules (
           rule_key TEXT PRIMARY KEY, enabled BOOLEAN NOT NULL DEFAULT false,
           updated_by BIGINT REFERENCES users(id), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
         );
         CREATE TABLE IF NOT EXISTS hr_rule_events (
           event_id UUID NOT NULL, action_key TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'pending'
             CHECK (status IN ('pending','complete','failed')), attempts INTEGER NOT NULL DEFAULT 0,
           payload JSONB NOT NULL DEFAULT '{}'::jsonb, last_error TEXT,
           created_at TIMESTAMPTZ NOT NULL DEFAULT now(), completed_at TIMESTAMPTZ,
           PRIMARY KEY(event_id, action_key)
         );
         ALTER TABLE hr_rule_events ADD COLUMN IF NOT EXISTS payload JSONB NOT NULL DEFAULT '{}'::jsonb;
         ALTER TABLE hr_rule_events ADD COLUMN IF NOT EXISTS last_error TEXT;
         CREATE INDEX IF NOT EXISTS ix_hr_rule_events_pending ON hr_rule_events(created_at) WHERE status='pending';
         CREATE TABLE IF NOT EXISTS hr_notifications (
           id UUID PRIMARY KEY DEFAULT gen_random_uuid(), user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
           event_id UUID NOT NULL, rule_key TEXT NOT NULL, title TEXT NOT NULL, body TEXT NOT NULL,
           created_at TIMESTAMPTZ NOT NULL DEFAULT now(), read_at TIMESTAMPTZ, UNIQUE(event_id,user_id)
         );
         CREATE INDEX IF NOT EXISTS ix_hr_notifications_user_unread ON hr_notifications(user_id, created_at DESC) WHERE read_at IS NULL;
         INSERT INTO hr_rules(rule_key) VALUES
           ('employee.created'),('employee.updated'),('employee.archived'),
           ('leave.submitted'),('leave.decided'),('expense.submitted'),('expense.decided'),
           ('candidate.stage_changed'),('payroll.completed') ON CONFLICT DO NOTHING;
         CREATE OR REPLACE FUNCTION hr_record_history_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
           BEGIN RAISE EXCEPTION 'hr_record_history is append-only'; END; $$;
         DO $$ BEGIN
           IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname='hr_record_history_no_change' AND NOT tgisinternal) THEN
             CREATE TRIGGER hr_record_history_no_change BEFORE UPDATE OR DELETE ON hr_record_history FOR EACH ROW EXECUTE FUNCTION hr_record_history_append_only();
           END IF;
           IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname='hr_record_history_no_truncate' AND NOT tgisinternal) THEN
             CREATE TRIGGER hr_record_history_no_truncate BEFORE TRUNCATE ON hr_record_history FOR EACH STATEMENT EXECUTE FUNCTION hr_record_history_append_only();
           END IF;
         END $$;"#,
    )
    .await
    .map_err(|error| format!("synchronize records and rules schema: {error}"))
}

pub async fn reset_test_data(database_url: &str) -> Result<(), String> {
    let mut connection = AsyncPgConnection::establish(database_url)
        .await
        .map_err(|error| format!("connect to isolated test database: {error}"))?;
    diesel_async::SimpleAsyncConnection::batch_execute(
        &mut connection,
        "BEGIN; \
         ALTER TABLE audit_logs DISABLE TRIGGER USER; \
         ALTER TABLE hr_record_history DISABLE TRIGGER USER; \
         TRUNCATE TABLE hr_rule_events, hr_rules, hr_record_unique_claims, hr_record_history, hr_records, refresh_tokens, password_resets, audit_logs, users RESTART IDENTITY CASCADE; \
         ALTER TABLE hr_record_history ENABLE TRIGGER USER; \
         ALTER TABLE audit_logs ENABLE TRIGGER USER; \
         COMMIT;",
    )
    .await
    .map_err(|error| format!("reset isolated test database: {error}"))
}

async fn sync_table(connection: &mut AsyncPgConnection, table: &Table) -> Result<(), String> {
    let exists = sql_query(
        "SELECT table_name AS name FROM information_schema.tables \
         WHERE table_schema = current_schema() AND table_name = $1",
    )
    .bind::<Text, _>(table.name)
    .load::<NameRow>(connection)
    .await
    .map_err(|error| format!("inspect {}: {error}", table.name))?
    .into_iter()
    .next()
    .is_some();

    if !exists {
        let definitions = table
            .columns
            .iter()
            .map(column_ddl)
            .collect::<Vec<_>>()
            .join(", ");
        diesel_async::SimpleAsyncConnection::batch_execute(
            connection,
            &format!(
                "CREATE TABLE IF NOT EXISTS {} ({definitions})",
                quote(table.name)
            ),
        )
        .await
        .map_err(|error| format!("create {}: {error}", table.name))?;
    }

    let existing = sql_query(
        "SELECT column_name AS name FROM information_schema.columns \
         WHERE table_schema = current_schema() AND table_name = $1",
    )
    .bind::<Text, _>(table.name)
    .load::<NameRow>(connection)
    .await
    .map_err(|error| format!("inspect {} columns: {error}", table.name))?
    .into_iter()
    .map(|row| row.name)
    .collect::<std::collections::HashSet<_>>();

    for column in table
        .columns
        .iter()
        .filter(|column| !existing.contains(column.name))
    {
        let ddl = column_ddl(column);
        diesel_async::SimpleAsyncConnection::batch_execute(
            connection,
            &format!(
                "ALTER TABLE {} ADD COLUMN IF NOT EXISTS {ddl}",
                quote(table.name)
            ),
        )
        .await
        .map_err(|error| format!("add {}.{}: {error}", table.name, column.name))?;
    }

    for index in table.indexes {
        diesel_async::SimpleAsyncConnection::batch_execute(connection, index)
            .await
            .map_err(|error| format!("synchronize index for {}: {error}", table.name))?;
    }
    Ok(())
}

fn column_ddl(column: &Column) -> String {
    let kind = match column.kind {
        ColumnType::Identity => "BIGINT GENERATED BY DEFAULT AS IDENTITY",
        ColumnType::BigInt => "BIGINT",
        ColumnType::Integer => "INTEGER",
        ColumnType::Text => "TEXT",
        ColumnType::Boolean => "BOOLEAN",
        ColumnType::Uuid => "UUID",
        ColumnType::Timestamptz => "TIMESTAMPTZ",
    };
    let mut ddl = format!("{} {kind}", quote(column.name));
    if column.primary_key {
        ddl.push_str(" PRIMARY KEY");
    }
    if !column.nullable {
        ddl.push_str(" NOT NULL");
    }
    if let Some(default) = column.default {
        ddl.push_str(" DEFAULT ");
        ddl.push_str(default);
    }
    ddl
}

fn quote(identifier: &str) -> String {
    format!("\"{identifier}\"")
}

async fn ensure_constraints(connection: &mut AsyncPgConnection) -> Result<(), String> {
    diesel_async::SimpleAsyncConnection::batch_execute(
        connection,
        r#"DO $$ BEGIN
          IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'users_role_check'
                     AND pg_get_constraintdef(oid) NOT LIKE '%recruiter%') THEN
            RAISE EXCEPTION 'legacy users_role_check blocks new roles; apply the reviewed manual schema change before startup';
          END IF;
          IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'users_role_check') THEN
            ALTER TABLE users ADD CONSTRAINT users_role_check
              CHECK (role IN ('employee', 'manager', 'finance', 'hr_admin', 'recruiter', 'payroll_admin'));
          END IF;
          IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'users_status_check') THEN
            ALTER TABLE users ADD CONSTRAINT users_status_check
              CHECK (status IN ('active', 'locked', 'disabled'));
          END IF;
          IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'users_failed_logins_check') THEN
            ALTER TABLE users ADD CONSTRAINT users_failed_logins_check CHECK (failed_logins >= 0);
          END IF;
          IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'refresh_tokens_user_id_fkey') THEN
            ALTER TABLE refresh_tokens ADD CONSTRAINT refresh_tokens_user_id_fkey
              FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE;
          END IF;
          IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'password_resets_user_id_fkey') THEN
            ALTER TABLE password_resets ADD CONSTRAINT password_resets_user_id_fkey
              FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE;
          END IF;
        END $$;"#,
    )
    .await
    .map_err(|error| format!("synchronize schema constraints: {error}"))
}

async fn ensure_audit_append_only(connection: &mut AsyncPgConnection) -> Result<(), String> {
    diesel_async::SimpleAsyncConnection::batch_execute(
        connection,
        r#"CREATE OR REPLACE FUNCTION audit_logs_append_only() RETURNS trigger
           LANGUAGE plpgsql AS $$ BEGIN
             RAISE EXCEPTION 'audit_logs is append-only';
           END; $$;
           DO $$ BEGIN
             IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'audit_logs_no_change'
                            AND NOT tgisinternal) THEN
               CREATE TRIGGER audit_logs_no_change BEFORE UPDATE OR DELETE ON audit_logs
               FOR EACH ROW EXECUTE FUNCTION audit_logs_append_only();
             END IF;
             IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'audit_logs_no_truncate'
                            AND NOT tgisinternal) THEN
               CREATE TRIGGER audit_logs_no_truncate BEFORE TRUNCATE ON audit_logs
               FOR EACH STATEMENT EXECUTE FUNCTION audit_logs_append_only();
             END IF;
           END $$;"#,
    )
    .await
    .map_err(|error| format!("secure audit log: {error}"))
}
